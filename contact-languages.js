(function () {
  const siteStorageKey = "mc_site_language";
  const legacyStorageKey = "mc_language";
  const fallbackLanguage = "en";

  function supportedLanguage(code) {
    return Object.prototype.hasOwnProperty.call(CONTACT_LANGUAGES, code);
  }

  function getInitialLanguage() {
    const saved = localStorage.getItem(siteStorageKey);
    if (saved && supportedLanguage(saved)) return saved;

    const legacy = localStorage.getItem(legacyStorageKey);
    if (legacy && supportedLanguage(legacy)) return legacy;

    const browser = (navigator.language || fallbackLanguage).toLowerCase();
    if (browser.startsWith("ko")) return "ko";
    if (browser.startsWith("ar")) return "ar";
    if (browser.startsWith("fr")) return "fr";
    if (browser.startsWith("vi")) return "vi";
    if (browser.startsWith("ja")) return "ja";
    if (browser.startsWith("zh-tw") || browser.startsWith("zh-hk") || browser.startsWith("zh-mo") || browser.includes("hant")) return "zh-Hant";
    if (browser.startsWith("zh") || browser.includes("hans")) return "zh-Hans";
    if (browser.startsWith("es")) return "es";
    if (browser.startsWith("de")) return "de";
    return fallbackLanguage;
  }

  function buildLanguageMenu(currentLanguage) {
    const select = document.getElementById("languageSelect");
    if (!select) return;

    select.innerHTML = "";
    Object.entries(CONTACT_LANGUAGES).forEach(([code, language]) => {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = language.label;
      option.selected = code === currentLanguage;
      select.appendChild(option);
    });

    select.addEventListener("change", () => applyLanguage(select.value));
  }

  function applyLanguage(code) {
    if (!supportedLanguage(code)) code = fallbackLanguage;
    const t = CONTACT_LANGUAGES[code];

    document.documentElement.lang = code;
    document.documentElement.dir = t.dir || "ltr";

    localStorage.setItem(siteStorageKey, code);
    localStorage.setItem(legacyStorageKey, (code === "en" || code === "fr") ? code : "en");

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.dataset.i18n;
      if (Object.prototype.hasOwnProperty.call(t, key)) {
        el.textContent = t[key];
      }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.dataset.i18nAria;
      if (Object.prototype.hasOwnProperty.call(t, key)) {
        el.setAttribute("aria-label", t[key]);
      }
    });

    if (t.title) document.title = t.title;

    const description = document.querySelector('meta[name="description"]');
    if (description && t.description) description.setAttribute("content", t.description);

    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle && t.title) ogTitle.setAttribute("content", t.title);

    const ogDescription = document.querySelector('meta[property="og:description"]');
    if (ogDescription && t.description) ogDescription.setAttribute("content", t.description);

    const select = document.getElementById("languageSelect");
    if (select) select.value = code;
  }

  function configureAppsMenu() {
    const navApps = document.getElementById("navApps");
    const menu = document.getElementById("appsMenu");
    if (!navApps || !menu) return;

    navApps.addEventListener("click", (event) => {
      event.stopPropagation();
      menu.style.display = menu.style.display === "block" ? "none" : "block";
    });

    document.addEventListener("click", (event) => {
      if (!menu.contains(event.target) && event.target !== navApps) {
        menu.style.display = "none";
      }
    });

    menu.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", () => {
        menu.style.display = "none";
      });
    });
  }

  document.addEventListener("DOMContentLoaded", () => {
    const initialLanguage = getInitialLanguage();
    configureAppsMenu();
    buildLanguageMenu(initialLanguage);
    applyLanguage(initialLanguage);
  });
})();
