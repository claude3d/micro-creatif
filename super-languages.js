(function () {
  const LANGUAGES = SUPER_LANGUAGES;
  const SITE_STORAGE_KEY = "mc_site_language";
  const LEGACY_STORAGE_KEY = "mc_language";
  const FALLBACK = "en";

  function supported(code) {
    return Object.prototype.hasOwnProperty.call(LANGUAGES, code);
  }

  function browserLanguage() {
    const code = (navigator.language || FALLBACK).toLowerCase();
    if (code.startsWith("ko")) return "ko";
    if (code.startsWith("ar")) return "ar";
    if (code.startsWith("fr")) return "fr";
    if (code.startsWith("vi")) return "vi";
    if (code.startsWith("ja")) return "ja";
    if (code.startsWith("zh-tw") || code.startsWith("zh-hk") || code.startsWith("zh-mo") || code.includes("hant")) return "zh-Hant";
    if (code.startsWith("zh") || code.includes("hans")) return "zh-Hans";
    if (code.startsWith("es")) return "es";
    if (code.startsWith("de")) return "de";
    return FALLBACK;
  }

  function initialLanguage() {
    const saved = localStorage.getItem(SITE_STORAGE_KEY);
    if (saved && supported(saved)) return saved;
    const legacy = localStorage.getItem(LEGACY_STORAGE_KEY);
    if (legacy && supported(legacy)) return legacy;
    return browserLanguage();
  }

  function buildLanguageMenu(current) {
    const select = document.getElementById("languageSelect");
    select.innerHTML = "";
    Object.entries(LANGUAGES).forEach(([code, pack]) => {
      const option = document.createElement("option");
      option.value = code;
      option.textContent = pack.label;
      option.selected = code === current;
      select.appendChild(option);
    });
    select.addEventListener("change", () => applyLanguage(select.value));
  }

  function applyCommon(t, code) {
    document.documentElement.lang = t.htmlLang || code;
    document.documentElement.dir = t.dir || "ltr";
    document.title = t.metaTitle;

    const map = {
      navHome:"navHome", navApps:"navApps", navAbout:"navAbout", navContact:"navContact",
      appRadec:"appRadec", appVirtualTelescope:"appVirtualTelescope",
      appSolAndStars:"appSolAndStars", appAlienSky:"appAlienSky",
      appTimeTravelSky:"appTimeTravelSky", locations:"locations"
    };
    Object.entries(map).forEach(([key,id]) => {
      const el = document.getElementById(id);
      if (el) el.textContent = t[key];
    });

    const nav = document.getElementById("siteNav");
    if (nav) nav.setAttribute("aria-label", t.mainNavigation);
    const select = document.getElementById("languageSelect");
    if (select) {
      select.setAttribute("aria-label", t.languageSelector);
      select.value = code;
    }

    localStorage.setItem(SITE_STORAGE_KEY, code);
    localStorage.setItem(LEGACY_STORAGE_KEY, (code === "en" || code === "fr") ? code : "en");
  }


  function appendBlocks(container, blocks) {
    container.innerHTML = "";
    blocks.forEach((block) => {
      const el = document.createElement(block.tag || "p");
      if (block.className) el.className = block.className;
      el.innerHTML = block.html;
      container.appendChild(el);
    });
  }

  function renderArticle(t) {
    document.getElementById("portraitHeader").textContent = t.header;
    document.getElementById("articleTitle").textContent = t.title;
    document.getElementById("articleSubtitle").textContent = t.subtitle;
    document.getElementById("byline").textContent = t.byline;
    document.getElementById("photo").alt = t.photoAlt || "Claude Johnson";
    document.getElementById("caption").textContent = t.caption;
    appendBlocks(document.getElementById("leftColumn"), t.left);
    appendBlocks(document.getElementById("rightColumn"), t.right);
    document.getElementById("backButton").textContent = t.back;
  }


  function applyLanguage(code) {
    if (!supported(code)) code = FALLBACK;
    const t = LANGUAGES[code];
    applyCommon(t, code);
    renderArticle(t);
  }

  function configureDropdown() {
    const dropdown = document.querySelector(".site-dropdown");
    const button = dropdown.querySelector(".site-apps-button");
    const submenu = dropdown.querySelector(".site-submenu");

    button.addEventListener("click", (event) => {
      event.stopPropagation();
      const isOpen = submenu.classList.toggle("open");
      button.setAttribute("aria-expanded", isOpen ? "true" : "false");
    });

    submenu.addEventListener("click", (event) => event.stopPropagation());

    document.addEventListener("click", () => {
      if (submenu.classList.contains("open")) {
        submenu.classList.remove("open");
        button.setAttribute("aria-expanded", "false");
      }
    });
  }

  document.addEventListener("DOMContentLoaded", () => {
    const lang = initialLanguage();
    buildLanguageMenu(lang);
    configureDropdown();
    applyLanguage(lang);
  });
})();
